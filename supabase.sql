-- Jalankan di Supabase > SQL Editor
create table if not exists public.likes (
  id bigint generated always as identity primary key,
  created_at timestamptz not null default now()
);

alter table public.likes enable row level security;

-- Semua pengunjung boleh melihat jumlah dan menambah like
drop policy if exists "likes_select" on public.likes;
create policy "likes_select" on public.likes for select using (true);
drop policy if exists "likes_insert" on public.likes;
create policy "likes_insert" on public.likes for insert with check (true);

-- Aktifkan realtime untuk tabel likes (counter live)
do $$
begin
  alter publication supabase_realtime add table public.likes;
exception when duplicate_object then
  null;
end $$;

-- Project portfolio content and admin access.
create table if not exists public.project_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.projects (
  id uuid primary key default gen_random_uuid(),
  category text not null check (category in ('websites', 'desktop', 'games', 'mobile')),
  name text not null,
  desc_en text not null default '',
  desc_id text not null default '',
  long_desc_en text not null default '',
  long_desc_id text not null default '',
  highlights_en text[] not null default '{}',
  highlights_id text[] not null default '{}',
  status_en text not null default 'In progress',
  status_id text not null default 'Sedang dikerjakan',
  created_date date not null default current_date,
  updated_date date not null default current_date,
  tech text[] not null default '{}',
  images text[] not null default '{}',
  live_url text,
  repo_url text,
  collab_with text[] not null default '{}',
  sort_order integer generated by default as identity,
  created_at timestamptz not null default now()
);

-- Upgrade an existing projects table without deleting its data.
alter table public.projects
  add column if not exists id uuid default gen_random_uuid(),
  add column if not exists category text not null default 'websites' check (category in ('websites', 'desktop', 'games', 'mobile')),
  add column if not exists name text not null default 'Untitled project',
  add column if not exists desc_en text not null default '',
  add column if not exists desc_id text not null default '',
  add column if not exists long_desc_en text not null default '',
  add column if not exists long_desc_id text not null default '',
  add column if not exists highlights_en text[] not null default '{}',
  add column if not exists highlights_id text[] not null default '{}',
  add column if not exists status_en text not null default 'In progress',
  add column if not exists status_id text not null default 'Sedang dikerjakan',
  add column if not exists created_date date not null default current_date,
  add column if not exists updated_date date not null default current_date,
  add column if not exists tech text[] not null default '{}',
  add column if not exists images text[] not null default '{}',
  add column if not exists live_url text,
  add column if not exists repo_url text,
  add column if not exists collab_with text[] not null default '{}',
  add column if not exists sort_order integer generated by default as identity,
  add column if not exists created_at timestamptz not null default now();

alter table public.project_admins enable row level security;
alter table public.projects enable row level security;

grant select on public.project_admins to authenticated;
grant select on public.projects to anon, authenticated;
grant insert, update, delete on public.projects to authenticated;

drop policy if exists "project_admins_read_self" on public.project_admins;
create policy "project_admins_read_self" on public.project_admins
  for select to authenticated using (user_id = (select auth.uid()));

drop policy if exists "projects_public_read" on public.projects;
create policy "projects_public_read" on public.projects
  for select to anon, authenticated using (true);

drop policy if exists "projects_admin_insert" on public.projects;
create policy "projects_admin_insert" on public.projects
  for insert to authenticated
  with check (exists (select 1 from public.project_admins where user_id = (select auth.uid())));

drop policy if exists "projects_admin_update" on public.projects;
create policy "projects_admin_update" on public.projects
  for update to authenticated
  using (exists (select 1 from public.project_admins where user_id = (select auth.uid())))
  with check (exists (select 1 from public.project_admins where user_id = (select auth.uid())));

drop policy if exists "projects_admin_delete" on public.projects;
create policy "projects_admin_delete" on public.projects
  for delete to authenticated
  using (exists (select 1 from public.project_admins where user_id = (select auth.uid())));

comment on column public.projects.images is
